import { NextResponse } from "next/server";
import { getSession } from "@/lib/auth/session";
import { signLaunchToken } from "@/lib/auth/launch-jwt";
import { db } from "@/lib/db";
import { env } from "@/lib/env";
import { logger } from "@/lib/logger";
import { logActivity } from "@/lib/portal/audit";
import { resolveProductEntitlement } from "@/lib/portal/entitlement";
import { storeLaunchToken } from "@/lib/portal/sso-token-store";

type LaunchTarget = {
  target: "lecturesuite" | "scholarsuite" | "researchsuite";
  ssoUrl: string;
};

/**
 * Allowlist: portal product slug → canonical product identifier (the token's
 * `target`/`aud`) and that product's SSO endpoint. A Map (not a plain object)
 * so prototype keys such as "constructor" can never resolve to an entry.
 *
 * `lecturercraft` / `scholarcraft` are the portal catalog's existing slugs
 * (lib/site-config.ts, Product rows); the canonical identifiers are accepted
 * as aliases so the catalog can be renamed later without touching this route.
 */
const LECTURESUITE: LaunchTarget = {
  target: "lecturesuite",
  ssoUrl: env.LECTURESUITE_SSO_URL,
};
const SCHOLARSUITE: LaunchTarget = {
  target: "scholarsuite",
  ssoUrl: env.SCHOLARSUITE_SSO_URL,
};
const RESEARCHSUITE: LaunchTarget = {
  target: "researchsuite",
  ssoUrl: env.RESEARCHSUITE_SSO_URL,
};
const PRODUCT_MAP: ReadonlyMap<string, LaunchTarget> = new Map([
  ["lecturercraft", LECTURESUITE],
  ["lecturesuite", LECTURESUITE],
  ["scholarcraft", SCHOLARSUITE],
  ["scholarsuite", SCHOLARSUITE],
  ["researchsuite", RESEARCHSUITE],
]);

/** Token-bearing redirects must never be cached or leak via Referer. */
function noStore<T extends NextResponse>(res: T): T {
  res.headers.set("Cache-Control", "no-store");
  res.headers.set("Referrer-Policy", "no-referrer");
  return res;
}

export async function GET(
  req: Request,
  { params }: { params: Promise<{ product: string }> }
) {
  const { product } = await params;

  const session = await getSession();
  if (!session) {
    const loginUrl = new URL("/login", env.NEXT_PUBLIC_APP_URL);
    return NextResponse.redirect(loginUrl);
  }

  const mapping = PRODUCT_MAP.get(product);
  if (!mapping) {
    return NextResponse.json({ error: "Unknown product" }, { status: 400 });
  }

  // The destination comes only from validated server config, never from the
  // request, so this route cannot be used as an open redirect.
  const destination = new URL(mapping.ssoUrl);
  if (destination.protocol !== "https:" && destination.protocol !== "http:") {
    return NextResponse.json({ error: "Product unavailable" }, { status: 500 });
  }

  const user = await db.user.findUnique({
    where: { id: session.sub },
    select: { email: true },
  });
  if (!user) {
    const loginUrl = new URL("/login", env.NEXT_PUBLIC_APP_URL);
    return NextResponse.redirect(loginUrl);
  }

  // Entitlement is enforced here, server-side, before any token exists. The
  // product SSO endpoints only accept tokens signed with CRAFT_LAUNCH_SECRET,
  // so no token means no product account is provisioned.
  const entitlement = await resolveProductEntitlement(
    session.sub,
    mapping.target
  );

  if (!entitlement.granted) {
    try {
      await logActivity(session.sub, "product.launch_denied", {
        product: mapping.target,
        slug: product,
        reason: entitlement.reason,
      });
    } catch (err) {
      logger.error("launch audit (denied) failed", {
        error: (err as Error).message,
      });
    }
    return noStore(
      NextResponse.json(
        { error: "You do not have active access to this product." },
        { status: 403 }
      )
    );
  }

  // A grant must leave an audit record; if it cannot be written, refuse.
  try {
    await logActivity(
      session.sub,
      "product.launch_granted",
      {
        product: mapping.target,
        slug: product,
        source: entitlement.source,
        subscriptionId: entitlement.subscriptionId,
      },
      entitlement.organizationId ?? undefined
    );
  } catch (err) {
    logger.error("launch audit (granted) failed", {
      error: (err as Error).message,
    });
    return noStore(
      NextResponse.json(
        { error: "Launch temporarily unavailable." },
        { status: 503 }
      )
    );
  }

  // State is generated by the product's /sso/initiate endpoint and passed here
  // as a query parameter. It binds this portal launch to exactly one browser
  // session, preventing login-CSRF.
  const incomingState = new URL(req.url).searchParams.get("state");

  // In secure mode (PORTAL_SERVICE_SECRET configured), state is mandatory — the
  // launch token must never appear in a browser-visible redirect URL. If the
  // browser arrived without state (e.g. a direct bookmark to this route), redirect
  // it through the product's /sso/initiate endpoint, which generates browser-bound
  // state and redirects back here with ?state=<state>.
  if (!incomingState && env.PORTAL_SERVICE_SECRET) {
    // Derive initiate URL: append /initiate to the product's SSO callback URL.
    // e.g. https://app.lecturesuite.com/api/auth/sso → …/api/auth/sso/initiate
    const initiateUrl = new URL(destination.toString());
    initiateUrl.pathname =
      initiateUrl.pathname.replace(/\/*$/, "") + "/initiate";
    return noStore(NextResponse.redirect(initiateUrl.toString()));
  }

  const token = await signLaunchToken(session.sub, user.email, mapping.target);

  if (incomingState && env.PORTAL_SERVICE_SECRET) {
    // Secure path: store the token server-side keyed by state so the product
    // backend can retrieve it via a service-to-service call.  The launch JWT
    // never appears in the browser-visible redirect URL this way.
    try {
      await storeLaunchToken(incomingState, token);
    } catch (err) {
      logger.error("launch sso-token store failed", {
        error: (err as Error).message,
      });
      return noStore(
        NextResponse.json(
          { error: "Launch temporarily unavailable." },
          { status: 503 }
        )
      );
    }
    destination.searchParams.set("state", incomingState);
    // No "token" param in URL — LectureSuite fetches it from /api/portal/sso-token
  } else {
    // Legacy / dev path: embed the token in the redirect URL.
    // Only acceptable when PORTAL_SERVICE_SECRET is not configured (local dev).
    destination.searchParams.set("token", token);
    if (incomingState) {
      destination.searchParams.set("state", incomingState);
    }
  }

  return noStore(NextResponse.redirect(destination.toString()));
}
